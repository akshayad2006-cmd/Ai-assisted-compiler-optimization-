#include "llvm/llvm_generator.h"

#include <map>
#include <set>
#include <sstream>
#include <string>

namespace {

std::string storageName(const Operand& operand) {
    if (operand.isTemporary()) {
        return "%temp_" + operand.name;
    }
    if (operand.isVariable()) {
        return "%var_" + operand.name;
    }
    return "";
}

void collectOperand(const Operand& operand, std::set<std::string>& storage) {
    const std::string name = storageName(operand);
    if (!name.empty()) {
        storage.insert(name);
    }
}

}  // namespace

std::string generateLlvmIr(const TacProgram& program, std::string& error) {
    error.clear();

    std::set<std::string> storage;

    for (const Instruction& inst : program.instructions) {
        if (inst.opcode == Opcode::PRINT) {
            collectOperand(inst.arg1, storage);
            continue;
        }

        collectOperand(inst.dest, storage);
        collectOperand(inst.arg1, storage);

        if (inst.isBinary()) {
            collectOperand(inst.arg2, storage);
        }
    }

    std::ostringstream out;

    out << "; Generated by AI-Assisted Compiler Optimization System\n"
        << "source_filename = \"aicompiler\"\n\n"
        << "@.fmt_in = private unnamed_addr constant [3 x i8] c\"%d\\00\", align 1\n"
        << "@.fmt_out = private unnamed_addr constant [4 x i8] c\"%d\\0A\\00\", align 1\n"
        << "@.err = private unnamed_addr constant [26 x i8] c\"Runtime arithmetic error\\0A\\00\", align 1\n\n"
        << "declare i32 @scanf(ptr, ...)\n"
        << "declare i32 @printf(ptr, ...)\n"
        << "declare i32 @puts(ptr)\n"
        << "declare void @exit(i32)\n"
        << "declare void @llvm.trap()\n"
        << "declare { i32, i1 } @llvm.sadd.with.overflow.i32(i32, i32)\n"
        << "declare { i32, i1 } @llvm.ssub.with.overflow.i32(i32, i32)\n"
        << "declare { i32, i1 } @llvm.smul.with.overflow.i32(i32, i32)\n\n"
        << "define i32 @main() {\n"
        << "entry:\n";

    for (const std::string& name : storage) {
        out << "  " << name << " = alloca i32, align 4\n";
    }

    out << "  br label %body\n\n"
        << "body:\n";

    int reg = 0;
    int block = 0;

    const auto nextReg = [&]() {
        return "%r" + std::to_string(++reg);
    };

    const auto nextBlock = [&]() {
        return "checked_" + std::to_string(++block);
    };

    const auto loadOperand = [&](const Operand& operand) -> std::string {
        if (operand.isConstant()) {
            return std::to_string(operand.value);
        }

        if (operand.isVariable() || operand.isTemporary()) {
            const std::string result = nextReg();
            out << "  " << result << " = load i32, ptr "
                << storageName(operand) << ", align 4\n";
            return result;
        }

        return "";
    };

    for (const Instruction& inst : program.instructions) {
        if (inst.opcode == Opcode::INPUT) {
            const std::string fmt = nextReg();
            out << "  " << fmt
                << " = getelementptr inbounds [3 x i8], ptr @.fmt_in, i64 0, i64 0\n"
                << "  " << nextReg()
                << " = call i32 (ptr, ...) @scanf(ptr "
                << fmt << ", ptr " << storageName(inst.dest) << ")\n";
            continue;
        }

        if (inst.opcode == Opcode::PRINT) {
            const std::string value = loadOperand(inst.arg1);
            const std::string fmt = nextReg();

            out << "  " << fmt
                << " = getelementptr inbounds [4 x i8], ptr @.fmt_out, i64 0, i64 0\n"
                << "  " << nextReg()
                << " = call i32 (ptr, ...) @printf(ptr "
                << fmt << ", i32 " << value << ")\n";
            continue;
        }

        if (inst.opcode == Opcode::COPY) {
            const std::string value = loadOperand(inst.arg1);
            out << "  store i32 " << value << ", ptr "
                << storageName(inst.dest) << ", align 4\n";
            continue;
        }

        if (inst.isBinary()) {
            const std::string left = loadOperand(inst.arg1);
            const std::string right = loadOperand(inst.arg2);
            const std::string result = nextReg();

            if (inst.opcode == Opcode::DIV) {
                const std::string isZero = nextReg();
                const std::string isMin = nextReg();
                const std::string isNegOne = nextReg();
                const std::string isOverflow = nextReg();
                const std::string isInvalid = nextReg();
                const std::string safeBlock = nextBlock();

                out << "  " << isZero << " = icmp eq i32 " << right << ", 0\n"
                    << "  " << isMin << " = icmp eq i32 " << left << ", -2147483648\n"
                    << "  " << isNegOne << " = icmp eq i32 " << right << ", -1\n"
                    << "  " << isOverflow << " = and i1 " << isMin << ", " << isNegOne << "\n"
                    << "  " << isInvalid << " = or i1 " << isZero << ", " << isOverflow << "\n"
                    << "  br i1 " << isInvalid << ", label %runtime_error, label %" << safeBlock << "\n\n"
                    << safeBlock << ":\n"
                    << "  " << result << " = sdiv i32 " << left << ", " << right << "\n";
                // The next instruction must be emitted in the safe block.
            } else {
                const char* intrinsic = nullptr;

                switch (inst.opcode) {
                    case Opcode::ADD:
                        intrinsic = "llvm.sadd.with.overflow.i32";
                        break;
                    case Opcode::SUB:
                        intrinsic = "llvm.ssub.with.overflow.i32";
                        break;
                    case Opcode::MUL:
                        intrinsic = "llvm.smul.with.overflow.i32";
                        break;
                    default:
                        error = "Unsupported TAC arithmetic opcode.";
                        return "";
                }

                const std::string pair = nextReg();
                const std::string value = nextReg();
                const std::string overflow = nextReg();
                const std::string safeBlock = nextBlock();

                out << "  " << pair << " = call { i32, i1 } @" << intrinsic
                    << "(i32 " << left << ", i32 " << right << ")\n"
                    << "  " << value << " = extractvalue { i32, i1 } " << pair << ", 0\n"
                    << "  " << overflow << " = extractvalue { i32, i1 } " << pair << ", 1\n"
                    << "  br i1 " << overflow << ", label %runtime_error, label %" << safeBlock << "\n\n"
                    << safeBlock << ":\n";

                out << "  store i32 " << value << ", ptr "
                    << storageName(inst.dest) << ", align 4\n";
                continue;
            }

            out << "  store i32 " << result << ", ptr "
                << storageName(inst.dest) << ", align 4\n";
            continue;
        }

        error = "Unsupported TAC instruction.";
        return "";
    }

    out << "  ret i32 0\n\n"
        << "runtime_error:\n"
        << "  call i32 @puts(ptr @.err)\n"
        << "  call void @exit(i32 1)\n"
        << "  unreachable\n"
        << "}\n";

    return out.str();
}
